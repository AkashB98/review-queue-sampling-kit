"""CLI: generate / sample / estimate / report / check / demo.

SYNTHETIC DATA ONLY -- every case is generated by a seeded script; no
real review data, no network, no API keys.

Exit codes:
  check : 0 = every headline claim holds on the seeded data,
          1 = a claim does not hold, 2 = bad input
  others: 0 = success, 2 = usage / IO error
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from generator import (DEFAULT_SEED, generate_queue, segment_sizes,  # noqa: E402
                       true_overall_rate, true_segment_rates)
from report import build_report  # noqa: E402
from sampling import (DEFAULT_BUDGET, DEFAULT_PI_FLOOR, DESIGNS,  # noqa: E402
                      run_design)

EXIT_OK, EXIT_FAIL, EXIT_ERROR = 0, 1, 2


def _dump(obj):
    print(json.dumps(obj, indent=2, sort_keys=True))


def _validate_budget(budget, queue_size):
    if budget < 1:
        raise ValueError("budget must be >= 1")
    if budget > queue_size:
        raise ValueError("budget exceeds queue size")


def _queue(args):
    return generate_queue(seed=args.seed,
                          miscalibrated=getattr(args, "miscalibrated", False))


def cmd_generate(args):
    cases = _queue(args)
    _dump({"size": len(cases), "seed": args.seed,
           "miscalibrated": bool(getattr(args, "miscalibrated", False)),
           "segment_sizes": segment_sizes(cases),
           "true_overall_error_rate": round(true_overall_rate(cases), 6),
           "true_segment_error_rates": {
               k: round(v, 6)
               for k, v in sorted(true_segment_rates(cases).items())}})
    return EXIT_OK


def cmd_sample(args):
    cases = _queue(args)
    _validate_budget(args.budget, len(cases))
    result = run_design(cases, args.design, args.budget, args.sample_seed,
                        pi_floor=args.pi_floor)
    _dump({"design": args.design, "budget": args.budget,
           "n_sampled": result["n_sampled"]})
    return EXIT_OK


def cmd_estimate(args):
    cases = _queue(args)
    _validate_budget(args.budget, len(cases))
    out = {d: run_design(cases, d, args.budget, args.sample_seed,
                         pi_floor=args.pi_floor) for d in DESIGNS}
    _dump({"budget": args.budget, "pi_floor": args.pi_floor,
           "true_overall_error_rate": round(true_overall_rate(cases), 6),
           "designs": out})
    return EXIT_OK


def cmd_report(args):
    _dump(build_report(budget=args.budget, pi_floor=args.pi_floor))
    return EXIT_OK


def cmd_check(args):
    if getattr(args, "input", None) and not os.path.exists(args.input):
        print(f"error: input not found: {args.input}", file=sys.stderr)
        return EXIT_ERROR
    if args.budget < 1:
        print("error: budget must be >= 1", file=sys.stderr)
        return EXIT_ERROR
    report = build_report(budget=args.budget, pi_floor=args.pi_floor)
    for name, held in sorted(report["claims"].items()):
        print(f"  {name}: {held}")
    if report["claims"]["all_headline_claims_hold"]:
        print("check PASS: all headline claims hold on the seeded data")
        return EXIT_OK
    print("check FAIL: a headline claim does not hold")
    return EXIT_FAIL


def cmd_demo(args):
    import demo as demo_mod
    try:
        return demo_mod.run()
    except AssertionError as exc:
        print(f"demo FAILED: {exc}", file=sys.stderr)
        return EXIT_FAIL


def build_parser():
    p = argparse.ArgumentParser(
        prog="cli.py",
        description="Review-queue sampling kit (synthetic data only).")
    sub = p.add_subparsers(dest="cmd", required=True)

    sp = sub.add_parser("generate", help="summarise the seeded queue")
    sp.add_argument("--seed", type=int, default=DEFAULT_SEED)
    sp.add_argument("--miscalibrated", action="store_true")
    sp.set_defaults(func=cmd_generate)

    for name, fn, helptext in (
            ("sample", cmd_sample, "draw one design's sample"),
            ("estimate", cmd_estimate, "all designs' estimates at a budget")):
        sp = sub.add_parser(name, help=helptext)
        sp.add_argument("--budget", type=int, default=DEFAULT_BUDGET)
        sp.add_argument("--seed", type=int, default=DEFAULT_SEED)
        sp.add_argument("--sample-seed", type=int, default=1001)
        sp.add_argument("--pi-floor", type=float, default=DEFAULT_PI_FLOOR)
        sp.add_argument("--miscalibrated", action="store_true")
        if name == "sample":
            sp.add_argument("--design", choices=list(DESIGNS), default="srs")
        sp.set_defaults(func=fn)

    sp = sub.add_parser("report", help="full report as JSON")
    sp.add_argument("--budget", type=int, default=DEFAULT_BUDGET)
    sp.add_argument("--pi-floor", type=float, default=DEFAULT_PI_FLOOR)
    sp.set_defaults(func=cmd_report)

    sp = sub.add_parser("check", help="CI gate: 0 claims hold / 1 not / 2 error")
    sp.add_argument("--budget", type=int, default=DEFAULT_BUDGET)
    sp.add_argument("--pi-floor", type=float, default=DEFAULT_PI_FLOOR)
    sp.add_argument("--input", default=None)
    sp.set_defaults(func=cmd_check)

    sub.add_parser("demo", help="run the end-to-end demo").set_defaults(
        func=cmd_demo)
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except (OSError, ValueError, KeyError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_ERROR


if __name__ == "__main__":
    sys.exit(main())
